// Regenerates example.js (the page's example state) from a capture CSV with columns
// t (seconds), dx, dy, device (raw device counts).
// Usage: node tools/make-example.mjs path/to/capture.csv
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { analyze } from '../analysis.js';

const csv = process.argv[2];
if (!csv) { console.error('usage: node tools/make-example.mjs <capture.csv>'); process.exit(2); }
const here = path.dirname(fileURLToPath(import.meta.url));

const rows = readFileSync(csv, 'utf8').trim().split(/\r?\n/).slice(1).map((l) => l.split(','));
const counts = new Map();
rows.forEach((r) => counts.set(r[3], (counts.get(r[3]) || 0) + 1));
const dev = [...counts.entries()].sort((a, b) => b[1] - a[1])[0][0];
const samples = rows.filter((r) => r[3] === dev)
  .map((r) => ({ t: Number(r[0]) * 1000, dx: Number(r[1]), dy: Number(r[2]) }))
  .sort((a, b) => a.t - b.t);

const res = analyze(samples);
const r2 = (v) => Math.round(v * 100) / 100;
const example = {
  note: 'Precomputed from a real capture. Strokes are summed [dx, dy] device counts.',
  result: {
    n: res.n, median: r2(res.median), weightedMedian: r2(res.weightedMedian), std: r2(res.std), se: r2(res.se),
    rightMedian: r2(res.rightMedian), leftMedian: r2(res.leftMedian)
  },
  strokes: res.strokes.map((s) => [Math.round(s.dx), Math.round(s.dy)])
};

const out = '// Generated by tools/make-example.mjs - do not edit by hand.\n' +
  'export const EXAMPLE = ' + JSON.stringify(example) + ';\n';
writeFileSync(path.join(here, '..', 'example.js'), out);
console.log('wrote example.js', out.length, 'bytes;', JSON.stringify(example.result));
