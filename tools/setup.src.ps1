function Invoke-Install($Arg) {
    $script:Tx = New-Tx
    $tx = $script:Tx
    # ownership from an earlier run (only a valid marker counts) is carried forward, never downgraded
    $prior = Read-Marker
    if ($prior) { $tx.PriorDriver = [bool]$prior.installedDriver; $tx.PriorAppDir = [bool]$prior.createdAppDir }
    if (Test-Path -LiteralPath $MarkerPath -PathType Leaf) { try { $tx.OrigMarkerBytes = [IO.File]::ReadAllBytes($MarkerPath) } catch { } }

    Step 'Checking prerequisites' '檢查先決條件'
    $net = Get-ItemProperty -LiteralPath 'HKLM:\SOFTWARE\Microsoft\NET Framework Setup\NDP\v4\Full' -Name Release -ErrorAction SilentlyContinue
    if (-not $net -or $net.Release -lt 461808) {
        Fail '.NET Framework 4.7.2 or newer is required (Windows Update / Windows 10 1803+ includes it). Aborting.' '需要 .NET Framework 4.7.2 或更新版本（Windows Update 或 Windows 10 1803 以上已內建）。已中止。' @() 7
    }
    Ok '.NET Framework release {0} (>= 461808)' '.NET Framework 版本 {0}（>= 461808）' @($net.Release)

    $script:StageDir = New-StageDir
    if ($DryRun) { Say 'Dry run: staging in a temp folder ({0}); a real run stages in an administrators-only folder.' '試跑：暫存在暫存資料夾（{0}）；正式執行會暫存在只有系統管理員能存取的資料夾。' 'Gray' '  ' @($script:StageDir) }
    else { Ok 'Staging folder {0} (administrators + SYSTEM only).' '暫存資料夾 {0}（只有系統管理員與 SYSTEM 可存取）。' @($script:StageDir) }

    $vc = Get-ItemProperty -LiteralPath 'HKLM:\SOFTWARE\Microsoft\VisualStudio\14.0\VC\Runtimes\X64' -Name Installed -ErrorAction SilentlyContinue
    if ($vc -and $vc.Installed -eq 1) {
        Ok 'Visual C++ x64 runtime is installed.' 'Visual C++ x64 執行階段已安裝。'
    } elseif ($DryRun) {
        Dry 'Download {0} into the staging folder, require a valid Microsoft Authenticode signature, run it with /install /quiet /norestart' '下載 {0} 到暫存資料夾，要求有效的 Microsoft 簽章，然後以 /install /quiet /norestart 執行' @($VcUrl)
    } else {
        Say 'Visual C++ x64 runtime missing; downloading from Microsoft.' '缺少 Visual C++ x64 執行階段，從 Microsoft 下載。'
        $vcExe = Join-Path $script:StageDir 'vc_redist.x64.exe'
        Save-Download $VcUrl $vcExe
        $sig = Get-AuthenticodeSignature -LiteralPath $vcExe
        if ($sig.Status -ne 'Valid' -or -not $sig.SignerCertificate -or $sig.SignerCertificate.Subject -notmatch 'O=Microsoft Corporation') {
            Fail 'vc_redist.x64.exe does not carry a valid Microsoft signature (status: {0}). Aborting.' 'vc_redist.x64.exe 沒有有效的 Microsoft 簽章（狀態：{0}）。已中止。' @($sig.Status) 5
        }
        $p = Start-Process -FilePath $vcExe -ArgumentList '/install', '/quiet', '/norestart' -PassThru
        if (-not (Wait-ChildProcess $p 600)) { Fail 'The VC++ runtime installer did not finish within 10 minutes and was stopped.' 'VC++ 執行階段安裝程式在 10 分鐘內沒有完成，已被終止。' @() 7 }
        if (@(0, 1638, 3010) -notcontains $p.ExitCode) {
            Fail 'VC++ runtime installer failed (exit code {0}).' 'VC++ 執行階段安裝失敗（結束代碼 {0}）。' @($p.ExitCode) 7
        }
        Ok 'Visual C++ x64 runtime installed (exit code {0}).' 'Visual C++ x64 執行階段已安裝（結束代碼 {0}）。' @($p.ExitCode)
    }

    Step 'Downloading Raw Accel v{0}' '下載 Raw Accel v{0}' @($RawAccelVersion)
    Say '{0}' '{0}' 'Gray' '  ' @($ZipUrl)
    [byte[]]$zipBytes = Get-RawAccelZipBytes
    if (-not (Test-ZipHash $zipBytes)) {
        Fail 'SHA256 mismatch! expected {0}, got {1}. Aborting; nothing was installed.' 'SHA256 不符！預期 {0}，實際 {1}。已中止，沒有安裝任何東西。' @($ZipSha256, (Get-BytesSha256 $zipBytes)) 4
    }
    Ok 'SHA256 verified: {0}' 'SHA256 驗證通過：{0}' @($ZipSha256)
    $table = Get-ZipFileTable
    if (-not (Test-ZipEntries $zipBytes $table)) { Fail 'The archive contents do not match the official file list. Nothing was installed.' '壓縮檔內容與官方檔案清單不符。沒有安裝任何東西。' @() 4 }
    Expand-VerifiedZip $zipBytes $script:StageDir $table
    Ok 'All {0} files match their pinned SHA256.' '全部 {0} 個檔案都符合預先固定的 SHA256。' @($table.Count)
    $zipBytes = $null

    $sys = Get-AuthenticodeSignature -LiteralPath (Join-Path $script:StageDir 'driver\rawaccel.sys')
    if ($sys.Status -ne 'Valid') {
        Fail 'driver\rawaccel.sys signature is not valid (status: {0}). Aborting.' 'driver\rawaccel.sys 簽章無效（狀態：{0}）。已中止。' @($sys.Status) 5
    }
    Ok 'rawaccel.sys Authenticode signature is valid ({0}).' 'rawaccel.sys 簽章有效（{0}）。' @($sys.SignerCertificate.Subject)

    # ---- new rotation = what the driver applies now + what the website measured
    Step 'Working out the rotation' '計算旋轉角度'
    $driverActive = Test-DriverActive $script:StageDir $script:StageDir
    if ($Arg.Kind -eq 'Measured' -and $script:DriverProbeFailed) {
        Fail 'Could not tell whether the Raw Accel driver is running (the system query failed), so the rotation it applies now is unknown. Nothing was changed.' '無法判斷 Raw Accel 驅動程式有沒有在運作（系統查詢失敗），所以不知道它目前套用的旋轉角度。沒有變更任何東西。' @() 1
    }
    $active = 0.0
    if ($Arg.Kind -eq 'Measured') {
        if ($driverActive) {
            try { $active = Get-ActiveRotation $script:StageDir $script:StageDir }
            catch {
