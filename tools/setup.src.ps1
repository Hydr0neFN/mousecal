                else { throw }
            }
        }
        $newRot = Get-NewRotation $active $Arg.Value
        Say 'current {0} deg -> new {1} deg   (measured {2} deg added to the active rotation)' '目前 {0}° -> 新 {1}°（把量到的 {2}° 加到目前套用的旋轉上）' 'White' '  ' @((Format-Rotation $active), (Format-Rotation $newRot), (Format-Rotation $Arg.Value))
    } else {
        if ($driverActive) { try { $active = Get-ActiveRotation $script:StageDir $script:StageDir } catch { $active = 0.0 } }
        $newRot = Get-NewRotation 0.0 $Arg.Value
        Say 'current {0} deg -> new {1} deg   (absolute value from -Rotation)' '目前 {0}° -> 新 {1}°（-Rotation 指定的絕對值）' 'White' '  ' @((Format-Rotation $active), (Format-Rotation $newRot))
    }
    $rotText = Format-Rotation $newRot

    # ---- settings.json (generated up front and validated before anything is changed)
    Step 'Preparing settings.json (rotation {0} deg)' '產生 settings.json（旋轉 {0} 度）' @($rotText)
    $existing = Test-Path -LiteralPath $SettingsPath
    if ($existing) {
        $base = [IO.File]::ReadAllText($SettingsPath)
        Say 'Existing {0} found: only "Degrees of rotation" will change; a backup is kept and everything else stays as it is.' '找到既有的 {0}：只會修改「Degrees of rotation」，其他設定維持原樣，並保留備份。' 'Gray' '  ' @($SettingsPath)
    } else {
        $base = $SettingsTemplate
        Say 'No existing settings.json: using the default template (no acceleration + your rotation).' '沒有既有的 settings.json：使用預設模板（無加速 + 你的旋轉角度）。'
    }
    $keys = Get-RotationKeyCount $base
    if ($keys -gt 1) { Warn 'settings.json has {0} profiles; the rotation is set in all of them.' 'settings.json 有 {0} 個設定檔，已全部設為同一旋轉角度。' @($keys) }
    $newJson = Set-RotationInJson $base $newRot
    $cand = Join-Path $script:StageDir 'settings.candidate.json'
    Write-Utf8NoBom $cand $newJson
    Test-SettingsJson $script:StageDir $cand $script:StageDir
    Ok 'Raw Accel accepts the settings (DriverConfig.Convert reported no errors).' 'Raw Accel 接受這份設定（DriverConfig.Convert 沒有回報錯誤）。'

    $filterPresent = Test-RawAccelFilter
    if ($filterPresent) {
        if ($existing) { Warn 'A rawaccel driver is already installed. Only the rotation in {0} will change; all your other Raw Accel settings stay.' '已經安裝過 rawaccel 驅動程式。只會改 {0} 裡的旋轉角度，你其他的 Raw Accel 設定都保留。' @($SettingsPath) }
        else { Warn 'A rawaccel driver is already installed, but there is no settings.json at {0}; one will be created (no acceleration + your rotation). Settings kept elsewhere are not touched.' '已經安裝過 rawaccel 驅動程式，但 {0} 沒有 settings.json；會建立一份（無加速 + 你的旋轉角度）。放在其他地方的設定不會動。' @($SettingsPath) }
    }
    $oldTask = Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue

    # ---- DRY RUN stops here after listing the actions
    if ($DryRun) {
        Step 'Actions a real run would perform' '正式執行時會做的事'
        Dry 'Lock {0} (non-recursive) and {1} + {2} (recursive) to SYSTEM + Administrators full control, Users read & execute only, inheritance removed (icacls, SIDs); again after settings.json is written' '把 {0}（不含子項目）以及 {1}、{2}（含所有子項目）鎖成只有 SYSTEM 與系統管理員可完全控制、一般使用者只能讀取與執行、移除繼承（icacls，使用 SID）；寫入 settings.json 後再鎖一次' @($InstallRoot, $AppDir, (Get-HandlerDir))
        Dry 'Copy the {0} verified files to {1} (only new/changed ones), re-check their hashes' '把 {0} 個已驗證的檔案複製到 {1}（只複製新的／有變的），並再次核對雜湊值' @($table.Count, $AppDir)
        Dry 'Write the marker {0} (so uninstall only removes what we installed; written again, with the driver flag, BEFORE installer.exe runs)' '寫入標記 {0}（讓解除安裝只移除我們裝的東西；在執行 installer.exe 之前會再寫一次並記下驅動程式旗標）' @($MarkerPath)
        if ($existing) { Dry 'Back up {0} to settings.json.bak-<timestamp>' '將 {0} 備份為 settings.json.bak-<時間戳記>' @($SettingsPath) }
        Dry 'Write {0} (UTF-8, no BOM), rotation = {1}; validate it with the installed wrapper.dll' '寫入 {0}（UTF-8，無 BOM），旋轉 = {1}；用已安裝的 wrapper.dll 驗證' @($SettingsPath, $rotText)
        if ($filterPresent) { Dry 'Skip installer.exe (rawaccel driver already registered)' '略過 installer.exe（rawaccel 驅動程式已註冊）' }
        else { Dry 'Run the verified installer.exe hidden (copies rawaccel.sys, creates the service, adds the filter last); wait up to 60 s for filter + file + service, then stop it' '隱藏執行已驗證的 installer.exe（複製 rawaccel.sys、建立服務、最後加入篩選器）；最多等 60 秒讓篩選器、檔案、服務都出現，然後結束它' }
        if (-not $driverActive) {
            Dry 'Re-check for running games, then restart the mouse devices (pnputil /restart-device) so the driver attaches without a reboot' '再確認沒有遊戲在執行，然後重新啟動滑鼠裝置（pnputil /restart-device），讓驅動程式不用重開機就能掛上去'
            Dry 'Health check: if a mouse device that was OK before the restart is not OK afterwards (even when the driver runs) -> undo everything (uninstall driver, restore files) and stop with exit code 8' '健康檢查：如果重新啟動前正常的滑鼠裝置在重新啟動後不正常（即使驅動程式在運作）-> 全部還原（移除驅動程式、還原檔案）並以結束代碼 8 停止'
        }
        if ($oldTask) { Dry 'Replace the existing scheduled task "{0}" (an older version of this tool created it){1}' '取代既有的工作排程「{0}」（這個工具舊版建立的）{1}' @($TaskName, $(if (Test-Path -LiteralPath $VbsPath) { ' and delete ' + $VbsPath } else { '' })) }
        Dry 'Register scheduled task "{0}": runs as SYSTEM (highest), at startup (delay 15 s) and at every logon (delay 10 s), 2 min limit -> "{1}" "{2}"' '註冊工作排程「{0}」：以 SYSTEM（最高權限）執行，開機後延遲 15 秒、每次登入後延遲 10 秒，限時 2 分鐘 -> "{1}" "{2}"' @($TaskName, (Join-Path $AppDir 'writer.exe'), $SettingsPath)
        Dry 'Register the mousecal:// URL protocol: write handler.vbs, handler.ps1 and a copy of this script to {0} (administrators + SYSTEM may write, Users read only); registry {1} (default "URL:mousecal Protocol", "URL Protocol" = "") with shell\open\command = {2}' '註冊 mousecal:// 網址通訊協定：把 handler.vbs、handler.ps1 和這個腳本的副本寫到 {0}（只有系統管理員與 SYSTEM 能修改，一般使用者唯讀）；登錄 {1}（預設值「URL:mousecal Protocol」、「URL Protocol」=「」），shell\open\command = {2}' @((Get-HandlerDir), $ProtocolKey, (Get-ProtocolCommand))
        Dry 'If no game runs: apply now with writer.exe (must exit 0, then the active rotation is read back); otherwise leave it to the next startup/logon' '如果沒有遊戲在執行：立即用 writer.exe 套用（結束代碼必須是 0，並讀回目前旋轉確認）；否則留給下次開機／登入時套用'
        Write-Host ''
        Say 'Dry run finished: download, every file hash, signature and settings validation all passed. Nothing was installed.' '試跑結束：下載、每個檔案的雜湊值、簽章與設定驗證都通過。沒有安裝任何東西。' 'Green' ''
        return 0
    }

    # =============================== real run: transactional from here on
    try {
        # ---- 1. files
        Step 'Installing files to {0}' '安裝檔案到 {0}' @($AppDir)
        $tx.Mutated = $true
        if (-not (Test-Path -LiteralPath $AppDir)) { New-Item -ItemType Directory -Path $AppDir -Force | Out-Null; $tx.AppDirCreated = $true }
        # Administrators / SYSTEM only may write here, BEFORE anything is copied or hash-checked (writer.exe runs as SYSTEM
        # at every startup): also when the folder already existed with user write access.
        Protect-AppDir $InstallRoot -NoRecurse
        Protect-AppDir $AppDir
        foreach ($rel in $table.Keys) {
            $src = Join-Path $script:StageDir ($rel.Replace('/', '\'))
            $dest = Join-Path $AppDir ($rel.Replace('/', '\'))
            $had = Test-Path -LiteralPath $dest
            if ($had -and (Get-FileSha256 $dest) -eq $table[$rel]) { continue }
            New-Item -ItemType Directory -Path (Split-Path $dest) -Force | Out-Null
            if ($had) {
                # differs from the official file: keep the original (admin-only staging) so a rollback can put it back
                $bk = Join-Path $script:StageDir ('.originals\' + $rel.Replace('/', '\'))
                New-Item -ItemType Directory -Path (Split-Path $bk) -Force | Out-Null
                Copy-Item -LiteralPath $dest -Destination $bk -Force
                $tx.Overwritten += @{ Dest = $dest; Backup = $bk }
            }
            try { Copy-Item -LiteralPath $src -Destination $dest -Force }
            catch { Fail 'Could not write {0}: {1}. If Raw Accel is open, close it and run the command again.' '無法寫入 {0}：{1}。如果 Raw Accel 正在開啟，請關閉它再執行一次指令。' @($dest, $_.Exception.Message) 1 }
            if (-not $had) { $tx.CreatedFiles += $dest }
        }
        foreach ($rel in $table.Keys) {
            if ((Get-FileSha256 (Join-Path $AppDir ($rel.Replace('/', '\')))) -ne $table[$rel]) { Fail 'Installed file {0} does not match the official hash.' '已安裝的檔案 {0} 與官方雜湊值不符。' @($rel) 4 }
        }
        $sysInst = Get-AuthenticodeSignature -LiteralPath (Join-Path $AppDir 'driver\rawaccel.sys')
        if ($sysInst.Status -ne 'Valid') { Fail 'Installed driver\rawaccel.sys signature is not valid ({0}).' '已安裝的 driver\rawaccel.sys 簽章無效（{0}）。' @($sysInst.Status) 5 }
        Write-Marker $tx
        if ($tx.Overwritten.Count -gt 0) {
            Warn '{0} existing file(s) in {1} differed from the official Raw Accel v1.7.1 and were replaced by the official ones. The originals are kept until setup finishes and are put back if setup fails.' '{1} 裡有 {0} 個既有檔案與官方 Raw Accel v1.7.1 不同，已換成官方檔案。原檔會保留到設定完成；如果設定失敗會放回去。' @($tx.Overwritten.Count, $AppDir)
        }
        Ok 'Files in place, hashes and driver signature verified.' '檔案已就緒，雜湊值與驅動程式簽章都已驗證。'

        # ---- 2. settings
        Step 'Writing settings' '寫入設定'
        if ($existing) {
            $tx.SettingsExisted = $true
            $tx.SettingsBytes = [IO.File]::ReadAllBytes($SettingsPath)
            $tx.BackupPath = Backup-Settings $SettingsPath
            Ok 'Backed up to {0}' '已備份到 {0}' @($tx.BackupPath)
        }
        $tx.SettingsWritten = $true
        Write-Utf8NoBom $SettingsPath $newJson
        Protect-AppDir $AppDir
        Test-SettingsJson $AppDir $SettingsPath $script:StageDir
        Ok 'Wrote {0} (rotation {1}); validated with the installed wrapper.dll.' '已寫入 {0}（旋轉 {1}）；已用安裝好的 wrapper.dll 驗證。' @($SettingsPath, $rotText)

        # ---- 3. driver
        Step 'Raw Accel driver' 'Raw Accel 驅動程式'
        $games = @(Get-RunningAntiCheatGames)
        if ($games.Count -gt 0) { Fail 'A game started during setup ({0}). Close it and run the command again; anything done was undone.' '設定期間有遊戲啟動（{0}）。請關閉它再執行一次指令；已做的變更都會還原。' @(($games -join ', ')) 6 }
        $installedNow = Install-RawAccelDriver $script:StageDir
        $tx.Mutated = $true
        if ($installedNow) { Write-Marker $tx }

        # ---- 4. restart devices + health check
        $driverActive = Test-DriverActive $AppDir $script:StageDir
        $gamesNow = @(Get-RunningAntiCheatGames)
        if (-not $driverActive) {
            if ($gamesNow.Count -gt 0) {
                Warn 'A game is running ({0}); the mouse devices are NOT restarted now. Reboot after closing it.' '有遊戲在執行（{0}），現在不重新啟動滑鼠裝置。關閉遊戲後請重新開機。' @(($gamesNow -join ', '))
            } else {
                $miceBefore = Get-MouseDeviceStatus
                Say 'Restarting mouse devices so the driver attaches (the pointer may freeze for a second)...' '重新啟動滑鼠裝置讓驅動程式掛上去（游標可能停頓一秒）……'
                $tx.DevicesRestarted = $true       # set first: a rollback restarts them again
                [void](Restart-MouseDevices)
                $driverActive = Test-DriverActive $AppDir $script:StageDir
                # a mouse that worked before and does not now is a failure, even if rawaccel reports Running
                # (it gets $MouseSettleSeconds seconds to come back or to reappear; devices that were already broken are ignored)
                $bad = @(Get-MouseRegressions $miceBefore)
                for ($i = 0; $bad.Count -gt 0 -and $i -lt $MouseSettleSeconds; $i++) { Start-Sleep -Seconds 1; $bad = @(Get-MouseRegressions $miceBefore) }
                if ($bad.Count -gt 0) {
                    Fail 'A mouse device that worked before is not working after installing the driver ({0}). Everything is being undone.' '安裝驅動程式後，原本正常的滑鼠裝置不能用了（{0}）。正在全部還原。' @(($bad -join ', ')) 8
                }
            }
        }

        # ---- 5. scheduled task (replaces the older VBS-style task of earlier versions)
        Step 'Startup task' '開機工作'
        if ($oldTask) {
            try { $tx.OldTaskXml = [string](Export-ScheduledTask -TaskName $TaskName); $tx.HadOldTask = $true } catch { }
        }
        if (Test-Path -LiteralPath $VbsPath) { $tx.OldVbsBytes = [IO.File]::ReadAllBytes($VbsPath) }
        $tx.TaskRegistered = $true
        Register-ApplyTask $SettingsPath
        if ($tx.OldVbsBytes) { Remove-Item -LiteralPath $VbsPath -Force }
        Ok 'Scheduled task "{0}" registered (SYSTEM; at startup after 15 s and at every logon after 10 s).' '工作排程「{0}」已註冊（SYSTEM；開機後 15 秒、每次登入後 10 秒）。' @($TaskName)
        if ($tx.OldVbsBytes) { Ok 'Removed the old {0}.' '已移除舊的 {0}。' @($VbsPath) }
        Write-Marker $tx

        # ---- 5b. one-click link (mousecal:// URL protocol). A failure here only costs the one-click
        # buttons (the copy-command flow keeps working), so it is a warning; a later failure rolls it back.
        Step 'One-click link (mousecal://)' '一鍵連結（mousecal://）'
        $tx.PriorProtocol = Test-UrlProtocolPresent
        $tx.ProtocolSnapshot = Get-UrlProtocolSnapshot
        $tx.ProtocolRegistered = $true
        $protocolOk = $false
        try {
            Register-UrlProtocol
            $protocolOk = $true
            Ok 'Registered the mousecal:// URL protocol; handler files are in {0} (administrators can write, everyone can read).' '已註冊 mousecal:// 網址通訊協定；處理程式檔案在 {0}（只有系統管理員能修改，所有人可讀取）。' @((Get-HandlerDir))
        } catch {
            Warn 'Could not set up the one-click link ({0}). Everything else is installed; the copy-command method on the website keeps working.' '無法設定一鍵連結（{0}）。其他都已安裝完成；網站上「複製指令」的方法仍然可用。' @($_.Exception.Message)
            try { if (-not $tx.PriorProtocol) { Unregister-UrlProtocol } else { Restore-UrlProtocolSnapshot $tx.ProtocolSnapshot } } catch { }
        }

        # ---- 6. apply now (never while a listed game runs)
        Write-Host ''
        $gamesNow = @(Get-RunningAntiCheatGames)
        if ($driverActive -and $gamesNow.Count -eq 0) {
            $writer = Join-Path $AppDir 'writer.exe'
            Assert-PinnedFile $writer 'writer.exe'
            $w = Start-Process -FilePath $writer -ArgumentList ('"{0}"' -f $SettingsPath) -WorkingDirectory $AppDir -WindowStyle Hidden -PassThru
            if (-not (Wait-ChildProcess $w $WriterTimeoutSec)) { Fail 'writer.exe did not finish within {0} seconds and was stopped. Everything is being undone.' 'writer.exe 在 {0} 秒內沒有完成，已被終止。正在全部還原。' @($WriterTimeoutSec) 1 }
            if ($w.ExitCode -ne 0) { Fail 'writer.exe failed to apply the settings (exit code {0}). Everything is being undone.' 'writer.exe 套用設定失敗（結束代碼 {0}）。正在全部還原。' @($w.ExitCode) 1 }
            $verified = $null     # $true = read back and equal, $false = read back and different, $null = could not read back
            try { $now = Get-ActiveRotation $AppDir $script:StageDir; $verified = ([math]::Abs($now - $newRot) -lt 0.01) } catch { $verified = $null }
            if ($verified -eq $true) {
                Say 'Done. The rotation of {0} deg is active now; no reboot needed. Go back to {1} and press "Measure again" (pass: |angle| < 1 deg).' '完成。{0} 度的旋轉已生效，不需要重新開機。回到 {1} 按「再量一次」（通過條件：|角度| < 1 度）。' 'Green' '' @($rotText, $SiteBase)
            } elseif ($null -eq $verified) {
                Say 'writer.exe finished (exit code 0) but the rotation could not be read back from the driver to confirm it. Reboot to be sure, then measure again on {0}.' 'writer.exe 已完成（結束代碼 0），但無法從驅動程式讀回旋轉角度來確認。為了確定，請重新開機，再到 {0} 量一次。' 'Yellow' '' @($SiteBase)
            } else {
                Say 'writer.exe finished (exit code 0) but the driver reports a different rotation ({0}). Reboot, then measure again on {1}.' 'writer.exe 已完成（結束代碼 0），但驅動程式回報的旋轉角度不同（{0}）。請重新開機，再到 {1} 量一次。' 'Yellow' '' @((Format-Rotation $now), $SiteBase)
            }
        } elseif ($driverActive) {
            Say 'Done, but a game is running ({0}) so the settings were NOT applied now. They apply at the next startup or logon.' '完成，但有遊戲在執行（{0}），所以現在沒有套用。下次開機或登入時才會套用。' 'Yellow' '' @(($gamesNow -join ', '))
        } else {
            Say 'Done. The driver needs a REBOOT to start; the settings apply by themselves after it. Then go back to {0} and press "Measure again" (pass: |angle| < 1 deg).' '完成。驅動程式需要重新開機才會啟動，設定會自動套用。重開機後回到 {0} 按「再量一次」（通過條件：|角度| < 1 度）。' 'Yellow' '' @($SiteBase)
        }
        if ($protocolOk) { Say 'Next time you re-measure, the website''s "One-click apply" button works without copying a command.' '下次重新量測後，網站上的「一鍵套用」按鈕就能直接套用，不用再複製指令。' }
        Say 'To remove everything later: use "One-click uninstall" (or "Copy uninstall command") on the website.' '之後要完全移除：到網站按「一鍵解除安裝」（或「複製解除安裝指令」）。'
        return 0
    }
    catch {
        $err = $_
        Invoke-Rollback
        throw $err
    }
}

# ======================================================================= main
function Invoke-MainCore {
    $ErrorActionPreference = 'Stop'
    $origModulePath = Repair-ModulePath
    $script:Tx = $null
    $script:SetupLock = $null
    try {
        Write-Host ''
        Say ('Mouse rotation setup (Raw Accel v{0})' -f $RawAccelVersion) ('滑鼠旋轉校正設定 (Raw Accel v{0})' -f $RawAccelVersion) 'White' ''
        if ($DryRun) { Say 'DRY RUN: nothing outside a temp folder will be changed.' '試跑模式：除了暫存資料夾，不會變更任何東西。' 'Magenta' '' }

        # ---- 1. arguments (exit 3)
        $arg = Resolve-Arguments
        if ($env:OS -ne 'Windows_NT') { Fail 'This script is for Windows only.' '這個腳本只適用於 Windows。' @() 7 }

        # ---- 2. games / anti-cheat (exit 6): read-only, so it comes before the admin check
        Assert-NoGameRunning

        # ---- 3. admin (exit 2)
        if (-not (Test-IsAdmin)) {
            if ($DryRun) {
                Say 'Not running as administrator (fine for a dry run; a real run needs it).' '目前不是系統管理員（試跑沒關係，正式執行必須是）。'
            } else {
                Write-Host ''
                Say 'Administrator rights are required. Press Win+R, paste the command, then press Ctrl+Shift+Enter (not just Enter) and click Yes on the UAC prompt. Nothing was changed.' '需要系統管理員權限。請按 Win+R、貼上指令，再按 Ctrl+Shift+Enter（不是只按 Enter），並在 UAC 按「是」。目前沒有任何變更。' 'Red' ''
                return 2
            }
        }

        # ---- 4. environment (exit 7)
        if (-not [Environment]::Is64BitProcess) {
            Fail 'Please use a 64-bit PowerShell (Windows Terminal opens one by default).' '請使用 64 位元的 PowerShell（Windows 終端機預設就是）。' @() 7
        }
        if ($env:PROCESSOR_ARCHITECTURE -eq 'ARM64') {
            Fail 'Raw Accel does not support ARM64 Windows.' 'Raw Accel 不支援 ARM64 版 Windows。' @() 7
        }
        [Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12

        # ---- 5. one real run at a time (-DryRun changes nothing and does not take the lock)
        if (-not $DryRun) {
            $script:SetupLock = Enter-SetupLock
            if (-not $script:SetupLock) {
                Write-Host ''
                Say 'Another mousecal setup is running right now. Wait for it to finish, then run this again. Nothing was changed.' '另一個 mousecal 設定正在執行。請等它結束後再執行一次。目前沒有任何變更。' 'Red' ''
                return 1
            }
        }

        if (-not $DryRun) { Clear-StaleStaging }     # leftovers of crashed runs; we hold the mutex, so none is in use

        if ($arg.Kind -eq 'Uninstall') { Invoke-Uninstall; return 0 }
        $rc = @(Invoke-Install $arg)
        return [int]$rc[$rc.Count - 1]
    }
    catch {
        Write-Host ''
        Write-Host ('  [error] ' + $_.Exception.Message) -ForegroundColor Red
        $c = $_.Exception.Data['ExitCode']
        $code = if ($c) { [int]$c } else { 1 }
        $h = Get-ErrorHint $code ([bool]$Uninstall)
        Say $h[0] $h[1] 'Yellow' '  [what to do] '
        return $code
    }
    finally {
        if (-not $DryRun) { Remove-StageDir }
        elseif ($script:StageDir -and (Test-Path -LiteralPath $script:StageDir)) { Remove-StageDir }
        if (-not $DryRun -and $script:Tx -and $script:Tx.RootCreated -and (Test-Path -LiteralPath $InstallRoot) -and -not (Get-ChildItem -LiteralPath $InstallRoot -Force)) {
            Remove-Item -LiteralPath $InstallRoot -Force -ErrorAction SilentlyContinue
        }
        if ($script:SetupLock) { Exit-SetupLock $script:SetupLock; $script:SetupLock = $null }
        if ($origModulePath) { $env:PSModulePath = $origModulePath }
    }
}

# Returns the exit code (does not call exit, so it is safe to dot-source or run in a live terminal).
function Invoke-Main {
    $r = @(Invoke-MainCore)
    $code = if ($r.Count -eq 0) { 1 } else { [int]$r[$r.Count - 1] }
    Invoke-Pause
    return $code
}

if ($env:MOUSECAL_NO_MAIN -ne '1') {
    $mousecalExit = Invoke-Main
    $global:LASTEXITCODE = $mousecalExit
    # Only a real script file may "exit" (never the pasted scriptblock: it would close the user's terminal).
    if ($PSCommandPath -and $MyInvocation.InvocationName -ne '.') { exit $mousecalExit }
}
