$RotationKeyPattern = '("Degrees of rotation"\s*:\s*)-?\d+(\.\d+)?([eE][+-]?\d+)?'
function Get-RotationKeyCount([string]$Json) { return ([regex]::Matches($Json, $RotationKeyPattern)).Count }

# Changes only the "Degrees of rotation" value(s); throws if the key is missing.
function Set-RotationInJson([string]$Json, [double]$Rot) {
    if ((Get-RotationKeyCount $Json) -lt 1) {
        Fail 'No "Degrees of rotation" key found in settings.json; refusing to guess.' 'settings.json 找不到「Degrees of rotation」欄位，不猜測。'
    }
    return [regex]::Replace($Json, $RotationKeyPattern, ('${1}' + (Format-Rotation $Rot)))
}

# new rotation = currently active rotation + measured residual (both in Raw Accel's
# clockwise-positive convention). Refuses (exit 3) beyond +-45 degrees.
function Get-NewRotation([double]$Active, [double]$Delta) {
    $new = [math]::Round($Active + $Delta, 2)
    if ([math]::Abs($new) -gt 45) {
        Fail 'The new rotation would be {0} deg (current {1} + measured {2}), beyond +-45. Nothing was changed.' '新的旋轉角度會是 {0}°（目前 {1}° + 量到 {2}°），超過 ±45°。沒有變更任何東西。' @((Format-Rotation $new), (Format-Rotation $Active), (Format-Rotation $Delta)) 3
    }
    return $new
}

