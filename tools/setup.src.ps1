# Parses a degrees argument with the invariant culture. Rejects commas (ambiguous decimal
# separator), NaN and Infinity. Returns a double; exit code 3 on any problem.
function ConvertTo-Degrees($Value, [string]$Name) {
    if ($Value -is [double] -or $Value -is [int] -or $Value -is [single] -or $Value -is [decimal]) { $d = [double]$Value }
    else {
        $s = if ($null -eq $Value) { '' } else { ([string]$Value).Trim() }
        if ($s -eq '') { Fail 'Missing value for -{0}.' '-{0} 缺少數值。' @($Name) 3 }
        if ($s.Contains(',')) { Fail 'Use a dot as the decimal separator in -{0} (got "{1}").' '-{0} 的小數點請用「.」（收到「{1}」）。' @($Name, $s) 3 }
        $d = 0.0
        if (-not [double]::TryParse($s, [Globalization.NumberStyles]::Float, [Globalization.CultureInfo]::InvariantCulture, [ref]$d)) {
            Fail '-{0} is not a number: "{1}".' '-{0} 不是數字：「{1}」。' @($Name, $s) 3
        }
    }
    Test-RotationValue $d
    return $d
}

function Get-FileSha256([string]$Path) {
    $sha = [Security.Cryptography.SHA256]::Create()
    $fs = [IO.File]::OpenRead($Path)
    try { return ([BitConverter]::ToString($sha.ComputeHash($fs)) -replace '-', '') }
    finally { $fs.Dispose(); $sha.Dispose() }
}
function Get-BytesSha256([byte[]]$Bytes) {
    $sha = [Security.Cryptography.SHA256]::Create()
    try { return ([BitConverter]::ToString($sha.ComputeHash($Bytes)) -replace '-', '') } finally { $sha.Dispose() }
}

# $true only when the zip (given as a file path OR as a [byte[]]) hashes to the pinned official SHA256.
