# $true when the rawaccel driver is running right now (filter attached). Sets
# $script:DriverProbeFailed when it could not be determined (CIM threw AND, if a verified
# DLL directory was given, GetActive() could not read the driver either); callers that need
# the answer for correctness (-Measured) must check that flag. GetActive() only succeeds
# while the driver is loaded.
$script:DriverProbeFailed = $false
function Test-DriverActive([string]$DllDir = '', [string]$WorkDir = '') {
    $script:DriverProbeFailed = $false
    $cimOk = $false
    try {
        $d = Get-CimInstance -ClassName Win32_SystemDriver -Filter "Name='rawaccel'" -ErrorAction Stop
        $cimOk = $true
        if ($d -and $d.State -eq 'Running') { return $true }
    } catch { }
    if (-not $DllDir -and -not $cimOk) {
        # no directory given: use the installed copies, but only if both DLLs are the official ones
        $t = Get-ZipFileTable
        try {
            if ((Get-FileSha256 (Join-Path $AppDir 'wrapper.dll')) -eq $t['wrapper.dll'] -and (Get-FileSha256 (Join-Path $AppDir 'Newtonsoft.Json.dll')) -eq $t['Newtonsoft.Json.dll']) { $DllDir = $AppDir }
        } catch { }
    }
    $wd = if ($WorkDir) { $WorkDir } else { $script:StageDir }   # never %TEMP%: the helper script runs elevated
    if ($DllDir -and $wd) {
        try { [void](Get-ActiveRotation $DllDir $wd); return $true }
        catch { if ($_.Exception.Data['ExitCode'] -eq 3) { return $true } }     # profiles disagree: the driver IS running
    }
    if (-not $cimOk) { $script:DriverProbeFailed = $true }
    return $false
}

function Format-Rotation([double]$v) {
