# Validates -Rotation / -Measured / -Uninstall. Returns @{ Kind = 'Uninstall' | 'Rotation' | 'Measured'; Value = double }.
function Resolve-Arguments {
    $hasR = -not [string]::IsNullOrWhiteSpace([string]$Rotation)
    $hasM = -not [string]::IsNullOrWhiteSpace([string]$Measured)
    if ($Uninstall) {
        if ($hasR -or $hasM) { Fail 'Do not combine -Uninstall with -Rotation or -Measured.' '-Uninstall 不能和 -Rotation 或 -Measured 一起使用。' @() 3 }
        return @{ Kind = 'Uninstall'; Value = 0.0 }
    }
    if ($hasR -and $hasM) { Fail 'Use either -Rotation (absolute) or -Measured (added to the current rotation), not both.' '-Rotation（絕對值）和 -Measured（加到目前旋轉）只能擇一。' @() 3 }
    if (-not $hasR -and -not $hasM) { Fail 'Missing -Measured <degrees> (from the website) or -Rotation <degrees>; or use -Uninstall.' '缺少 -Measured <度數>（網站量到的角度）或 -Rotation <度數>；或使用 -Uninstall。' @() 3 }
    if ($hasR) { return @{ Kind = 'Rotation'; Value = (ConvertTo-Degrees $Rotation 'Rotation') } }
    return @{ Kind = 'Measured'; Value = (ConvertTo-Degrees $Measured 'Measured') }
}

# ================================================================== uninstall
# Removes the apply task and the legacy VBS (honours -DryRun).
function Remove-ApplyTask {
    $hasTask = [bool](Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue)
    if ($hasTask) {
        if ($DryRun) { Dry 'Remove scheduled task "{0}"' '移除工作排程「{0}」' @($TaskName) }
        else { Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false; Ok 'Removed scheduled task "{0}"' '已移除工作排程「{0}」' @($TaskName) }
    } else { Say 'No scheduled task "{0}" found.' '找不到工作排程「{0}」。' 'Gray' '  ' @($TaskName) }
    if (Test-Path -LiteralPath $VbsPath) {
        if ($DryRun) { Dry 'Delete {0}' '刪除 {0}' @($VbsPath) }
        else { Remove-Item -LiteralPath $VbsPath -Force; Ok 'Deleted {0}' '已刪除 {0}' @($VbsPath) }
    }
}

# Path of an uninstaller.exe that matches the pinned official hash: the installed one if it
# is intact, otherwise the one from a freshly downloaded, fully verified official zip, staged
# in the admin-only folder.
function Get-VerifiedUninstaller {
    $local = Join-Path $AppDir 'uninstaller.exe'
    $table = Get-ZipFileTable
    if ((Test-Path -LiteralPath $local -PathType Leaf) -and (Get-FileSha256 $local) -eq $table['uninstaller.exe']) { return $local }
    Warn '{0} is missing or is not the official file; downloading the official Raw Accel v1.7.1 and using its verified uninstaller.exe instead.' '{0} 不存在或不是官方檔案；改為下載官方 Raw Accel v1.7.1，並使用其中已驗證的 uninstaller.exe。' @($local)
    [byte[]]$zip = Get-RawAccelZipBytes
    if (-not (Test-ZipHash $zip)) { Fail 'SHA256 mismatch for the downloaded Raw Accel zip. Nothing was removed.' '下載的 Raw Accel 壓縮檔 SHA256 不符。沒有移除任何東西。' @() 4 }
    if (-not (Test-ZipEntries $zip $table)) { Fail 'The archive contents do not match the official file list. Nothing was removed.' '壓縮檔內容與官方檔案清單不符。沒有移除任何東西。' @() 4 }
    Expand-VerifiedZip $zip $script:StageDir $table
    return (Join-Path $script:StageDir 'uninstaller.exe')
}

function Invoke-Uninstall {
    $needReboot = $false
    Step 'Uninstalling (only what this tool installed)' '解除安裝（只移除這個工具裝的東西）'

    # --- no marker: not ours. Only the apply task / legacy VBS (created by this tool or its older versions) go.
    $marker = Read-Marker
    if (-not $marker) {
        Remove-ApplyTask
        Remove-UrlProtocolStep
        if ((Test-Path -LiteralPath $InstallRoot) -or (Test-RawAccelFilter)) {
            Warn 'No mousecal install marker found: this Raw Accel was not installed by this tool, so its driver and files are left alone. To remove it, use Raw Accel''s own uninstaller.exe (in its folder).' '找不到 mousecal 的安裝標記：這份 Raw Accel 不是這個工具裝的，所以驅動程式和檔案都不動。要移除請用 Raw Accel 資料夾裡自己的 uninstaller.exe。'
        }
        Write-Host ''
        if ($DryRun) { Say 'Dry run finished. Nothing was changed.' '試跑結束，沒有變更任何東西。' 'Green' '' }
        else { Say 'Done. Only the apply task / script was removed.' '完成。只移除了套用設定的工作排程／腳本。' 'Green' '' }
        return
    }

    # --- driver first: the startup task stays until this succeeds, so a failure leaves a working setup
    $unExe = Join-Path $AppDir 'uninstaller.exe'
    if ($marker.installedDriver -and ((Test-RawAccelFilter) -or (Test-Path -LiteralPath $DriverSysPath))) {
        if ($DryRun) { Dry 'Use {0} if it matches the official hash (otherwise download and verify the official zip and use its uninstaller.exe), run it hidden, wait until the driver filter and file are gone, then stop it; restart the mouse devices' '若 {0} 符合官方雜湊值就使用它（否則下載並驗證官方壓縮檔，改用其中的 uninstaller.exe），隱藏執行、等驅動程式篩選器和檔案消失後結束它，並重新啟動滑鼠裝置' @($unExe) }
        else {
            $script:StageDir = New-StageDir
            $exe = Get-VerifiedUninstaller
            $r = Invoke-DriverTool $exe 'uninstall'
            if (-not $r.Ok) { Fail 'uninstaller.exe did not remove the driver within 60 seconds. Output: {0}' 'uninstaller.exe 在 60 秒內沒有移除驅動程式。輸出：{0}' @($r.Output) 8 }
            Ok 'Raw Accel driver unregistered.' 'Raw Accel 驅動程式已取消註冊。'
            [void](Restart-MouseDevices -All)
            if ((Test-DriverActive) -or $script:DriverProbeFailed) { $needReboot = $true }
        }
    } elseif (-not $marker.installedDriver) {
        Say 'The Raw Accel driver was already there before this tool; it is left installed.' '這個工具安裝之前就已經有 Raw Accel 驅動程式，所以保留它。'
    }

    Remove-ApplyTask
    Remove-UrlProtocolStep

    # --- files
    if ($marker.createdAppDir) {
        if (-not $DryRun -and (Test-Path -LiteralPath $AppDir -PathType Container) -and -not (Test-ReparsePoint $AppDir)) { [void](Remove-ReparsePoints $AppDir) }   # links are deleted, never followed
        $c = Get-OwnedFileClassification $AppDir
        if ($DryRun) {
            Dry 'Delete {0} files we installed from {1}' '從 {1} 刪除 {0} 個我們安裝的檔案' @($c.Known.Count, $AppDir)
            if ($c.Unknown.Count -gt 0) { Dry 'Leave {0} other file(s) alone: {1}' '保留 {0} 個其他檔案：{1}' @($c.Unknown.Count, ($c.Unknown -join ', ')) }
        } else {
            foreach ($rel in $c.Known) { Remove-Item -LiteralPath (Join-Path $AppDir ($rel.Replace('/', '\'))) -Force -ErrorAction SilentlyContinue }
            Remove-EmptyDirs $AppDir
            Ok 'Deleted {0} installed files.' '已刪除 {0} 個安裝的檔案。' @($c.Known.Count)
            if ($c.Unknown.Count -gt 0) { Warn 'Left {0} file(s) that this tool did not install in {1}: {2}' '保留 {1} 裡 {0} 個不是這個工具安裝的檔案：{2}' @($c.Unknown.Count, $AppDir, ($c.Unknown -join ', ')) }
        }
    } else {
        Say 'Raw Accel files were already there before this tool; they are left in place.' '這個工具安裝之前 Raw Accel 的檔案就已經存在，所以保留。'
    }
    if ($DryRun) { Dry 'Delete the marker {0}; delete {1} only if it is then empty' '刪除標記 {0}；{1} 只有在清空後才會刪除' @($MarkerPath, $InstallRoot) }
    else {
        Remove-Item -LiteralPath $MarkerPath -Force -ErrorAction SilentlyContinue
        Remove-StageDir
        if ((Test-Path -LiteralPath $InstallRoot) -and (Get-ChildItem -LiteralPath $InstallRoot -Force)) {
            Warn '{0} still holds files this tool did not install, so the folder is left in place.' '{0} 裡還有不是這個工具安裝的檔案，所以保留資料夾。' @($InstallRoot)
        } else { Remove-EmptyDirs $InstallRoot }
    }
    Write-Host ''
    if ($DryRun) { Say 'Dry run finished. Nothing was changed.' '試跑結束，沒有變更任何東西。' 'Green' '' }
    elseif ($needReboot) { Say 'Done. The driver may still be loaded: please REBOOT to finish removing it.' '完成。驅動程式可能仍在運作中：請重新開機才能完全移除。' 'Yellow' '' }
    else { Say 'Done. Raw Accel is removed; no reboot needed.' '完成。Raw Accel 已移除，不需要重新開機。' 'Green' '' }
}

