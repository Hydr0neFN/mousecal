function Get-RunningNames([string[]]$Names) {
    $procs = @()
    try { $procs = @(Get-Process -ErrorAction Stop | ForEach-Object { $_.ProcessName }) }
    catch { $procs = @([Diagnostics.Process]::GetProcesses() | ForEach-Object { $_.ProcessName }) }
    $running = @{}
    foreach ($p in $procs) { if ($p) { $running[$p.ToLowerInvariant()] = $p } }
    $hit = New-Object System.Collections.Generic.List[string]
    foreach ($n in $Names) { if ($running.ContainsKey($n.ToLowerInvariant())) { $hit.Add($running[$n.ToLowerInvariant()]) } }
    return $hit.ToArray()
}
