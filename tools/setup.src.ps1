# The exact text of the script being executed (works for -File and for
# [scriptblock]::Create((irm ...)) alike): the full script text of this function's own AST.
function Get-SelfScriptText {
    $t = $null
    try { $t = $MyInvocation.MyCommand.ScriptBlock.Ast.Extent.StartScriptPosition.GetFullScript() } catch { }
    if (-not $t -and $PSCommandPath) { try { $t = [IO.File]::ReadAllText($PSCommandPath) } catch { } }
    if (-not $t -or $t -notmatch 'function Register-UrlProtocol') {
        Fail 'Could not read the text of this script, so the one-click link cannot be set up.' '無法讀取這個腳本本身的內容，所以無法設定一鍵連結。' @() 1
    }
    return $t
}

# Folder permissions: administrators + SYSTEM full control, Users read & execute only (the
# handler runs as the normal user and must be able to read these files, never change them).
function Protect-HandlerDir([string]$Dir) { Protect-AppDir $Dir }

# Writes a file only when its content differs (the running script may be the very file).
function Write-IfChanged([string]$Path, [byte[]]$Bytes) {
    if ((Test-Path -LiteralPath $Path -PathType Leaf) -and (Get-BytesSha256 ([IO.File]::ReadAllBytes($Path))) -eq (Get-BytesSha256 $Bytes)) { return }
    [IO.File]::WriteAllBytes($Path, $Bytes)
}
function ConvertTo-HandlerBytes([string]$Text, [bool]$Bom) {
    $t = $Text -replace "`r?`n", "`r`n"
    if (-not $Bom) { return [Text.Encoding]::ASCII.GetBytes($t) }
    $enc = New-Object Text.UTF8Encoding ($true)
    return [byte[]]($enc.GetPreamble() + $enc.GetBytes($t))
}

function Test-UrlProtocolPresent([string]$Dir = '', [string]$Key = '') {
    if (-not $Dir) { $Dir = Get-HandlerDir }
    if (-not $Key) { $Key = $ProtocolKey }
    return ((Test-Path -LiteralPath $Key) -or (Test-Path -LiteralPath (Join-Path $Dir 'handler.vbs')))
}

# Writes handler.vbs, handler.ps1 and a copy of this script into the (locked-down) handler
# folder, then registers HKLM\SOFTWARE\Classes\mousecal. Throws on any problem.
function Register-UrlProtocol([string]$Dir = '', [string]$Key = '') {
    if (-not $Dir) { $Dir = Get-HandlerDir }
    if (-not $Key) { $Key = $ProtocolKey }
    $self = Get-SelfScriptText            # first: nothing is touched when it cannot be read
    if (-not (Test-Path -LiteralPath $Dir)) { New-Item -ItemType Directory -Path $Dir -Force | Out-Null }
    Protect-HandlerDir $Dir
    Write-IfChanged (Join-Path $Dir 'handler.vbs') (ConvertTo-HandlerBytes $HandlerVbsText $false)
    Write-IfChanged (Join-Path $Dir 'handler.ps1') (ConvertTo-HandlerBytes $HandlerPs1Text $true)
    Write-IfChanged (Join-Path $Dir 'setup.ps1') (ConvertTo-HandlerBytes $self $true)
    $cmdKey = $Key + '\shell\open\command'
    New-Item -Path $Key -Force | Out-Null
    Set-Item -LiteralPath $Key -Value 'URL:mousecal Protocol'
    New-ItemProperty -LiteralPath $Key -Name 'URL Protocol' -Value '' -PropertyType String -Force | Out-Null
    New-Item -Path $cmdKey -Force | Out-Null
    Set-Item -LiteralPath $cmdKey -Value (Get-ProtocolCommand $Dir)
}

# What the protocol key holds right now ($null = no key), so a failed re-run can put it back exactly.
function Get-UrlProtocolSnapshot([string]$Key = '') {
    if (-not $Key) { $Key = $ProtocolKey }
    if (-not (Test-Path -LiteralPath $Key)) { return $null }
    $k = Get-Item -LiteralPath $Key
    $snap = @{ HasDefault = ($k.GetValueNames() -contains ''); Default = $null; DefaultKind = 'String'; HasUrlProtocol = ($k.GetValueNames() -contains 'URL Protocol'); UrlProtocol = $null; UrlProtocolKind = 'String'; HasCommand = $false; Command = $null; CommandKind = 'String'; HasCommandDefault = $false }
    if ($snap.HasDefault) { $snap.Default = $k.GetValue('', $null, 'DoNotExpandEnvironmentNames'); $snap.DefaultKind = [string]$k.GetValueKind('') }
    if ($snap.HasUrlProtocol) { $snap.UrlProtocol = $k.GetValue('URL Protocol', $null, 'DoNotExpandEnvironmentNames'); $snap.UrlProtocolKind = [string]$k.GetValueKind('URL Protocol') }
    $ck = Join-Path $Key 'shell\open\command'
    if (Test-Path -LiteralPath $ck) {
        $c = Get-Item -LiteralPath $ck
        $snap.HasCommand = $true
        $snap.HasCommandDefault = ($c.GetValueNames() -contains '')
        if ($snap.HasCommandDefault) { $snap.Command = $c.GetValue('', $null, 'DoNotExpandEnvironmentNames'); $snap.CommandKind = [string]$c.GetValueKind('') }
    }
    return $snap
}

# Writes a registry value with its original kind (REG_EXPAND_SZ stays REG_EXPAND_SZ, not REG_SZ). '' = the default value.
function Set-RegistryValueKind([string]$Path, [string]$Name, $Value, [string]$Kind) {
    if (@('String', 'ExpandString', 'Binary', 'DWord', 'MultiString', 'QWord') -notcontains $Kind) { $Kind = 'String' }
    New-ItemProperty -LiteralPath $Path -Name $(if ($Name) { $Name } else { '(default)' }) -Value $Value -PropertyType $Kind -Force | Out-Null
}

function Restore-UrlProtocolSnapshot($Snap, [string]$Key = '') {
    if (-not $Key) { $Key = $ProtocolKey }
    if ($null -eq $Snap) { if (Test-Path -LiteralPath $Key) { Remove-Item -LiteralPath $Key -Recurse -Force }; return }
    if (-not (Test-Path -LiteralPath $Key)) { New-Item -Path $Key -Force | Out-Null }
    if ($Snap.HasDefault) { Set-RegistryValueKind $Key '' $Snap.Default $Snap.DefaultKind } else { Remove-ItemProperty -LiteralPath $Key -Name '(default)' -ErrorAction SilentlyContinue }
    if ($Snap.HasUrlProtocol) { Set-RegistryValueKind $Key 'URL Protocol' $Snap.UrlProtocol $Snap.UrlProtocolKind }
    else { Remove-ItemProperty -LiteralPath $Key -Name 'URL Protocol' -ErrorAction SilentlyContinue }
    $ck = Join-Path $Key 'shell\open\command'
    if ($Snap.HasCommand) {
        if (-not (Test-Path -LiteralPath $ck)) { New-Item -Path $ck -Force | Out-Null }
        if ($Snap.HasCommandDefault) { Set-RegistryValueKind $ck '' $Snap.Command $Snap.CommandKind } else { Remove-ItemProperty -LiteralPath $ck -Name '(default)' -ErrorAction SilentlyContinue }
    } elseif (Test-Path -LiteralPath (Join-Path $Key 'shell')) { Remove-Item -LiteralPath (Join-Path $Key 'shell') -Recurse -Force }
}

# Removes the registry key (only if it points at our handler) and our three files; the folder
# goes too when nothing else is in it. Never throws for things that are already gone.
function Unregister-UrlProtocol([string]$Dir = '', [string]$Key = '') {
    if (-not $Dir) { $Dir = Get-HandlerDir }
    if (-not $Key) { $Key = $ProtocolKey }
    if (Test-Path -LiteralPath $Key) {
        $cmd = ''
        $ck = Join-Path $Key 'shell\open\command'
        if (Test-Path -LiteralPath $ck) { $cmd = [string](Get-Item -LiteralPath $ck).GetValue('') }
        if (-not $cmd -or $cmd.IndexOf((Join-Path $Dir 'handler.vbs'), [StringComparison]::OrdinalIgnoreCase) -ge 0) {
            Remove-Item -LiteralPath $Key -Recurse -Force
        } else {
            Warn 'Registry key {0} points somewhere else ({1}); it is left alone.' '登錄機碼 {0} 指向別的地方（{1}）；不動它。' @($Key, $cmd)
        }
    }
    foreach ($n in 'handler.vbs', 'handler.ps1', 'setup.ps1') {
        $f = Join-Path $Dir $n
        if (Test-Path -LiteralPath $f) { Remove-Item -LiteralPath $f -Force }
    }
    Remove-EmptyDirs $Dir
}

# Uninstall step (honours -DryRun); a problem here never aborts the rest of the uninstall.
function Remove-UrlProtocolStep {
    if (-not (Test-UrlProtocolPresent)) { return }
    if ($DryRun) { Dry 'Remove the mousecal:// URL protocol ({0}) and the handler folder {1}' '移除 mousecal:// 網址通訊協定（{0}）與處理程式資料夾 {1}' @($ProtocolKey, (Get-HandlerDir)); return }
    try { Unregister-UrlProtocol; Ok 'Removed the mousecal:// URL protocol and {0}.' '已移除 mousecal:// 網址通訊協定與 {0}。' @((Get-HandlerDir)) }
    catch { Warn 'Could not fully remove the mousecal:// link ({0}). It is harmless; delete {1} and the registry key {2} by hand if you want.' '無法完整移除 mousecal:// 連結（{0}）。它無害；想清掉的話請手動刪除 {1} 與登錄機碼 {2}。' @($_.Exception.Message, (Get-HandlerDir), $ProtocolKey) }
}

