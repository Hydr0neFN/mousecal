# Restarts every present mouse device so the (un)installed filter driver attaches/detaches
# without a reboot. A failing device is tolerated. -All also restarts devices that are in an
# error state (used when rolling back). Returns the number restarted.
function Restart-MouseDevices([switch]$All) {
    if ($DryRun) { return 0 }
    $old = $ErrorActionPreference; $ErrorActionPreference = 'Continue'
    $done = 0
    try {
        $devs = @(Get-PnpDevice -Class Mouse -PresentOnly -ErrorAction SilentlyContinue | Where-Object { $All -or $_.Status -eq 'OK' })
        foreach ($d in $devs) {
            try {
                $pr = Invoke-BoundedProcess (Join-Path $env:SystemRoot 'System32\pnputil.exe') @('/restart-device', [string]$d.InstanceId) $WriterTimeoutSec
                if ($pr.Code -eq 0) { $done++ }
                else { Warn 'Could not restart device {0} (pnputil exit code {1}); continuing.' '無法重新啟動裝置 {0}（pnputil 結束代碼 {1}），繼續。' @($d.FriendlyName, $pr.Code) }
            } catch {
                Warn 'Could not restart device {0}: {1}; continuing.' '無法重新啟動裝置 {0}：{1}，繼續。' @($d.FriendlyName, $_.Exception.Message)
            }
        }
        if ($done -gt 0) { Start-Sleep -Seconds 2 }   # let the stack come back up
    } catch {
        Warn 'Could not list mouse devices: {0}' '無法列出滑鼠裝置：{0}' @($_.Exception.Message)
    } finally { $ErrorActionPreference = $old }
    return $done
}

