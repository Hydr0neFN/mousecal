# --------------------------------------------------------- driver installer
# Upstream (v1.7.1) installer.exe: copies driver\rawaccel.sys (path relative to the working
# directory) to %systemroot%\system32\drivers, creates/updates the demand-start service, and
# writes the rawaccel UpperFilters entry LAST; then prints "Press any key" and blocks.
# uninstaller.exe removes the UpperFilters entry FIRST, then renames the .sys to .tmp
# (deleted at reboot); it does not delete the service key; then also blocks.
function Read-SharedText([string]$Path) {
    if (-not (Test-Path -LiteralPath $Path)) { return '' }
    try {
        $fs = [IO.File]::Open($Path, 'Open', 'Read', 'ReadWrite')
        try { $sr = New-Object IO.StreamReader ($fs); return $sr.ReadToEnd() } finally { $fs.Dispose() }
    } catch { return '' }
}

function Test-ToolDone([string]$Mode, [string]$Output) {
    if ($Mode -eq 'install') {
        return ((Test-RawAccelFilter) -and (Test-Path -LiteralPath $DriverSysPath) -and (Test-Path -LiteralPath $ServiceKey))
    }
    return ((-not (Test-RawAccelFilter)) -and ((-not (Test-Path -LiteralPath $DriverSysPath)) -or $Output -match 'Removal complete|No installed driver found'))
}

# Runs installer.exe / uninstaller.exe hidden, polls until the work is observably done
# (registry filter + driver file + service key), then stops the process that waits for a key.
# Returns @{ Ok = bool; Output = text }.
function Invoke-DriverTool([string]$Exe, [string]$Mode, [int]$TimeoutSec = 60) {
    $outFile = Join-Path $script:StageDir ($Mode + '.out')
    $errFile = Join-Path $script:StageDir ($Mode + '.err')
    $p = Start-Process -FilePath $Exe -WorkingDirectory (Split-Path $Exe) -WindowStyle Hidden -PassThru -RedirectStandardOutput $outFile -RedirectStandardError $errFile
    $ok = $false; $text = ''
    try {
        $deadline = (Get-Date).AddSeconds($TimeoutSec)
        while ((Get-Date) -lt $deadline) {
            $text = (Read-SharedText $outFile) + (Read-SharedText $errFile)
            if (Test-ToolDone $Mode $text) { $ok = $true; break }
            if ($text -match '(?m)^Error:') { break }
            Start-Sleep -Milliseconds 500
        }
        if (-not $ok) {
            $text = (Read-SharedText $outFile) + (Read-SharedText $errFile)
            # uninstall: the filter (the part that matters) can be gone while the .sys is locked until reboot
            if ($Mode -eq 'uninstall' -and -not (Test-RawAccelFilter)) { $ok = $true }
        }
        if ($ok) { Start-Sleep -Seconds 1 }
    } finally {
        if (-not $p.HasExited) { Stop-Process -Id $p.Id -Force -ErrorAction SilentlyContinue }
    }
    return @{ Ok = $ok; Output = $text.Trim() }
}

# Installs the rawaccel driver using installer.exe in $Dir (a verified, admin-only folder
# that also holds driver\rawaccel.sys). Returns $true if it ran, $false if the driver was
# already registered (then nothing is touched).
function Install-RawAccelDriver([string]$Dir) {
    if (Test-RawAccelFilter) {
        Say 'rawaccel is already registered in UpperFilters; skipping installer.exe.' 'UpperFilters 已有 rawaccel，略過 installer.exe。'
        return $false
    }
    $exe = Join-Path $Dir 'installer.exe'
    Assert-PinnedFile $exe 'installer.exe'
    Assert-PinnedFile (Join-Path $Dir 'driver\rawaccel.sys') 'driver/rawaccel.sys'
    if ($script:Tx) {
        $script:Tx.DriverInstalled = $true      # set first: a half-done install is rolled back too
        Write-Marker $script:Tx                 # ... and recorded on disk first: a crash / closed window still leaves uninstall knowing about the driver
    }
    Say 'Running installer.exe (hidden). This can take up to a minute.' '執行 installer.exe（隱藏），最多需要一分鐘。'
    $r = Invoke-DriverTool $exe 'install'
    if (-not $r.Ok) {
        Fail 'The rawaccel driver did not finish registering within 60 seconds. Installer output: {0}' 'rawaccel 驅動程式在 60 秒內沒有完成註冊。安裝程式輸出：{0}' @($r.Output) 8
    }
    Ok 'Driver registered (file copied, service created, filter added).' '驅動程式已註冊（檔案已複製、服務已建立、篩選器已加入）。'
    return $true
}

