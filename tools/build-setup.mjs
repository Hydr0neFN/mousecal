// Generates the files that embed the Raw Accel settings template:
//   setup.ps1            <- tools/setup.src.ps1 with the template injected, ASCII only
//   settings-template.js <- the same template for the page's "advanced" section
//   setup-hash.js        <- SHA256 of the generated setup.ps1 (bytes as written), checked by the downloaded launcher
// Chinese text in the source becomes \uXXXX escapes (setup.ps1 decodes them at run time),
// so the served file survives any download encoding (e.g. irm without a charset).
// Usage: node tools/build-setup.mjs   (MOUSECAL_BUILD_OUT=<dir> writes the three files there instead; used by the tests)
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const out = process.env.MOUSECAL_BUILD_OUT || path.join(here, '..');
const norm = (s) => s.replace(/^﻿/, '').replace(/\r\n/g, '\n');

const template = norm(readFileSync(path.join(here, 'settings.template.json'), 'utf8')).replace(/\n+$/, '');
JSON.parse(template); // must be valid JSON
if (template.includes("\n'@")) throw new Error("template would terminate the here-string");

const zipFiles = norm(readFileSync(path.join(here, 'zip-files.txt'), 'utf8')).trim();
for (const line of zipFiles.split('\n')) {
  if (!/^[^|]+\|[0-9A-F]{64}$/.test(line)) throw new Error('bad zip-files.txt line: ' + line);
}
let src = norm(readFileSync(path.join(here, 'setup.src.ps1'), 'utf8'));
if (!src.includes('@@SETTINGS_TEMPLATE@@')) throw new Error('placeholder missing');
src = src.replace('@@SETTINGS_TEMPLATE@@', () => template);
if (!src.includes('@@ZIP_FILES@@')) throw new Error('zip placeholder missing');
src = src.replace('@@ZIP_FILES@@', () => zipFiles);

let escaped = '';
for (let i = 0; i < src.length; i++) {
  const c = src.charCodeAt(i);
  escaped += c > 126 ? '\\u' + c.toString(16).padStart(4, '0') : src[i];
}
const setupBytes = Buffer.from(escaped.replace(/\n/g, '\r\n'), 'latin1'); // ASCII only, so latin1 is exact
writeFileSync(path.join(out, 'setup.ps1'), setupBytes);
const sha256 = createHash('sha256').update(setupBytes).digest('hex');

const js = '// Generated by tools/build-setup.mjs from tools/settings.template.json - do not edit.\n' +
  'export const SETTINGS_TEMPLATE = ' + JSON.stringify(template) + ';\n';
writeFileSync(path.join(out, 'settings-template.js'), js);

const hashJs = '// Generated by tools/build-setup.mjs from the generated setup.ps1 - do not edit.\n' +
  '// The downloaded launcher (.cmd) refuses to run a setup.ps1 whose SHA256 differs from this value.\n' +
  "export const SETUP_SHA256 = '" + sha256 + "';\n";
writeFileSync(path.join(out, 'setup-hash.js'), hashJs);
console.log('wrote setup.ps1 (' + escaped.length + ' chars, ASCII), settings-template.js and setup-hash.js (' + sha256 + ')');
