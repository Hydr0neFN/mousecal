# ------------------------------------------------------------ bilingual output
# Chinese text is stored as \uXXXX escapes in the served file (see header).
function ZH([string]$s) {
    [regex]::Replace($s, '\\u([0-9a-fA-F]{4})', { param($m) [string][char][Convert]::ToInt32($m.Groups[1].Value, 16) })
}
function Format-Bi([string]$En, [string]$Zh, $A) {
    $z = ZH $Zh
    if ($null -ne $A -and @($A).Count -gt 0) { $En = [string]::Format($En, [object[]]@($A)); $z = [string]::Format($z, [object[]]@($A)) }
    return @($z, $En)
}
function Say([string]$En, [string]$Zh, [string]$Color = 'Gray', [string]$Prefix = '  ', [object[]]$A = @()) {
    $m = Format-Bi $En $Zh $A
    Write-Host ($Prefix + $m[0]) -ForegroundColor $Color
    Write-Host ($Prefix + $m[1]) -ForegroundColor DarkGray
}
function Step([string]$En, [string]$Zh, [object[]]$A = @()) { Write-Host ''; Say $En $Zh 'Cyan' '== ' $A }
function Ok([string]$En, [string]$Zh, [object[]]$A = @())   { Say $En $Zh 'Green' '  [ok] ' $A }
function Warn([string]$En, [string]$Zh, [object[]]$A = @()) { Say $En $Zh 'Yellow' '  [!] ' $A }
function Dry([string]$En, [string]$Zh, [object[]]$A = @())  { Say $En $Zh 'Magenta' '  [dry-run, would do] ' $A }
# Throws a bilingual error carrying the process exit code (see header).
function Fail([string]$En, [string]$Zh, [object[]]$A = @(), [int]$Code = 1) {
    $m = Format-Bi $En $Zh $A
    $ex = New-Object System.Exception ($m[0] + [Environment]::NewLine + $m[1])
    $ex.Data['ExitCode'] = $Code
    throw $ex
}

