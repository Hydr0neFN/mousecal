# Writes a file only when its content differs (the running script may be the very file).
function Write-IfChanged([string]$Path, [byte[]]$Bytes) {
    if ((Test-Path -LiteralPath $Path -PathType Leaf) -and (Get-BytesSha256 ([IO.File]::ReadAllBytes($Path))) -eq (Get-BytesSha256 $Bytes)) { return }
    [IO.File]::WriteAllBytes($Path, $Bytes)
}
function ConvertTo-HandlerBytes([string]$Text, [bool]$Bom) {
    $t = $Text -replace "`r?`n", "`r`n"
    if (-not $Bom) { return [Text.Encoding]::ASCII.GetBytes($t) }
    $enc = New-Object Text.UTF8Encoding ($true)
    return [byte[]]($enc.GetPreamble() + $enc.GetBytes($t))
}

