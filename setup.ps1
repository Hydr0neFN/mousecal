    }
    return $true
}

# Extracts the zip straight from memory. Every entry is hashed and compared with the pinned
# table BEFORE it is written; unexpected, missing or altered files abort with exit code 4.
function Expand-VerifiedZip([byte[]]$Bytes, [string]$Dest, $Table) {
    Add-Type -AssemblyName System.IO.Compression
    $ms = New-Object IO.MemoryStream (, $Bytes)
    $za = New-Object IO.Compression.ZipArchive ($ms, [IO.Compression.ZipArchiveMode]::Read)
    $seen = @{}
    try {
        foreach ($e in $za.Entries) {
            $name = $e.FullName.Replace('\', '/')
            if ($name.EndsWith('/')) { continue }
            if (-not $name.StartsWith('RawAccel/')) { Fail 'Unexpected path in the archive: {0}. Nothing was installed.' '\u58d3\u7e2e\u6a94\u5167\u6709\u975e\u9810\u671f\u7684\u8def\u5f91\uff1a{0}\u3002\u6c92\u6709\u5b89\u88dd\u4efb\u4f55\u6771\u897f\u3002' @($name) 4 }
            $rel = $name.Substring(9)
            if (-not $Table.ContainsKey($rel)) { Fail 'Unexpected file in the archive: {0}. Nothing was installed.' '\u58d3\u7e2e\u6a94\u5167\u6709\u975e\u9810\u671f\u7684\u6a94\u6848\uff1a{0}\u3002\u6c92\u6709\u5b89\u88dd\u4efb\u4f55\u6771\u897f\u3002' @($rel) 4 }
            if ($e.Length -gt 64MB) { Fail 'File too large in the archive: {0}.' '\u58d3\u7e2e\u6a94\u5167\u7684\u6a94\u6848\u904e\u5927\uff1a{0}\u3002' @($rel) 4 }
            $st = $e.Open()
            try { $buf = New-Object IO.MemoryStream; $st.CopyTo($buf) } finally { $st.Dispose() }
            $data = $buf.ToArray()
            if ((Get-BytesSha256 $data) -ne $Table[$rel]) {
                Fail 'Hash mismatch for {0}. Nothing was installed.' '{0} \u7684\u96dc\u6e4a\u503c\u4e0d\u7b26\u3002\u6c92\u6709\u5b89\u88dd\u4efb\u4f55\u6771\u897f\u3002' @($rel) 4
            }
            $target = [IO.Path]::Combine($Dest, $rel.Replace('/', '\'))
            $dir = [IO.Path]::GetDirectoryName($target)
            if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
            [IO.File]::WriteAllBytes($target, $data)
            $seen[$rel] = $true
        }
        foreach ($k in $Table.Keys) {
            if (-not $seen.ContainsKey($k)) { Fail 'The archive is missing {0}. Nothing was installed.' '\u58d3\u7e2e\u6a94\u7f3a\u5c11 {0}\u3002\u6c92\u6709\u5b89\u88dd\u4efb\u4f55\u6771\u897f\u3002' @($k) 4 }
        }
    } finally { $za.Dispose(); $ms.Dispose() }
}

# Verifies a file on disk against the pinned table (used right before running anything).
function Assert-PinnedFile([string]$Path, [string]$Rel) {
