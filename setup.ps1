# Validates -Rotation / -Measured / -Uninstall. Returns @{ Kind = 'Uninstall' | 'Rotation' | 'Measured'; Value = double }.
function Resolve-Arguments {
    $hasR = -not [string]::IsNullOrWhiteSpace([string]$Rotation)
    $hasM = -not [string]::IsNullOrWhiteSpace([string]$Measured)
    if ($Uninstall) {
        if ($hasR -or $hasM) { Fail 'Do not combine -Uninstall with -Rotation or -Measured.' '-Uninstall \u4e0d\u80fd\u548c -Rotation \u6216 -Measured \u4e00\u8d77\u4f7f\u7528\u3002' @() 3 }
        return @{ Kind = 'Uninstall'; Value = 0.0 }
    }
    if ($hasR -and $hasM) { Fail 'Use either -Rotation (absolute) or -Measured (added to the current rotation), not both.' '-Rotation\uff08\u7d55\u5c0d\u503c\uff09\u548c -Measured\uff08\u52a0\u5230\u76ee\u524d\u65cb\u8f49\uff09\u53ea\u80fd\u64c7\u4e00\u3002' @() 3 }
    if (-not $hasR -and -not $hasM) { Fail 'Missing -Measured <degrees> (from the website) or -Rotation <degrees>; or use -Uninstall.' '\u7f3a\u5c11 -Measured <\u5ea6\u6578>\uff08\u7db2\u7ad9\u91cf\u5230\u7684\u89d2\u5ea6\uff09\u6216 -Rotation <\u5ea6\u6578>\uff1b\u6216\u4f7f\u7528 -Uninstall\u3002' @() 3 }
    if ($hasR) { return @{ Kind = 'Rotation'; Value = (ConvertTo-Degrees $Rotation 'Rotation') } }
    return @{ Kind = 'Measured'; Value = (ConvertTo-Degrees $Measured 'Measured') }
}

