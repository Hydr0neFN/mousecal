# Undoes only what this run did, newest first. Never throws; says so if anything could not be undone.
function Invoke-Rollback {
    $tx = $script:Tx
    if (-not $tx -or -not $tx.Mutated) { return }
    Step 'Something failed: undoing the changes made so far' '\u767c\u751f\u932f\u8aa4\uff1a\u6b63\u5728\u9084\u539f\u5df2\u505a\u7684\u8b8a\u66f4'
    $problems = New-Object System.Collections.Generic.List[string]
    try {
        if ($tx.TaskRegistered) {
            try { Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false -ErrorAction Stop } catch { $problems.Add('task: ' + $_.Exception.Message) }
            if ($tx.OldTaskXml) { try { Register-ScheduledTask -TaskName $TaskName -Xml $tx.OldTaskXml -Force | Out-Null } catch { $problems.Add('previous task: ' + $_.Exception.Message) } }
            if ($tx.OldVbsBytes) { try { [IO.File]::WriteAllBytes($VbsPath, $tx.OldVbsBytes) } catch { $problems.Add('old VBS: ' + $_.Exception.Message) } }
        }
        if ($tx.ProtocolRegistered) {
            try {
                if (-not $tx.PriorProtocol) { Unregister-UrlProtocol }
                else { Restore-UrlProtocolSnapshot $tx.ProtocolSnapshot }      # the key's previous values, exactly (or no key if there was none)
            } catch { $problems.Add('mousecal:// link: ' + $_.Exception.Message) }
        }
        $restartedInRollback = $false
        if ($tx.DriverInstalled -and $script:StageDir) {
            $un =Join-Path $script:StageDir 'uninstaller.exe'
            if (Test-Path -LiteralPath $un) {
                try {
                    $u = Invoke-DriverTool $un 'uninstall'
                    if (-not $u.Ok) { $problems.Add('driver uninstall did not finish: ' + $u.Output) }
                    $restartedInRollback = $true
                    [void](Restart-MouseDevices -All)
                } catch { $problems.Add('uninstaller.exe: ' + $_.Exception.Message) }
            } else { $problems.Add('uninstaller.exe not available') }
        }
        # this run restarted the mice (so they re-attached the filter stack as it was then): restart them again
        # after the undo, also when the filter was there before this run and the driver was not uninstalled
        if ($tx.DevicesRestarted -and -not $restartedInRollback) {
            try { [void](Restart-MouseDevices -All) } catch { $problems.Add('restart mouse devices: ' + $_.Exception.Message) }
        }
        if ($tx.SettingsWritten) {
            try {
                if ($tx.SettingsExisted) { [IO.File]::WriteAllBytes($SettingsPath, $tx.SettingsBytes); if ($tx.BackupPath) { Remove-Item -LiteralPath $tx.BackupPath -Force -ErrorAction SilentlyContinue } }
                else { Remove-Item -LiteralPath $SettingsPath -Force -ErrorAction SilentlyContinue }
            } catch { $problems.Add('settings.json: ' + $_.Exception.Message) }
        }
        foreach ($f in $tx.CreatedFiles) { Remove-Item -LiteralPath $f -Force -ErrorAction SilentlyContinue }
        foreach ($o in $tx.Overwritten) {
            try { Copy-Item -LiteralPath $o.Backup -Destination $o.Dest -Force } catch { $problems.Add('restore ' + $o.Dest + ': ' + $_.Exception.Message) }
        }
        # the marker: put back exactly what was there before; delete it only if this run created it
        try {
            if ($tx.OrigMarkerBytes) { [IO.File]::WriteAllBytes($MarkerPath, $tx.OrigMarkerBytes) }
            else { Remove-Item -LiteralPath $MarkerPath -Force -ErrorAction SilentlyContinue }
        } catch { $problems.Add('marker: ' + $_.Exception.Message) }
        if ($tx.AppDirCreated) { Remove-EmptyDirs $AppDir }
    } catch { $problems.Add($_.Exception.Message) }
    if ($problems.Count -eq 0) { Ok 'Changes undone.' '\u5df2\u9084\u539f\u8b8a\u66f4\u3002' }
