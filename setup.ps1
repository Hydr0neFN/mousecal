# Removes the apply task and the legacy VBS (honours -DryRun).
function Remove-ApplyTask {
    $hasTask = [bool](Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue)
    if ($hasTask) {
        if ($DryRun) { Dry 'Remove scheduled task "{0}"' '\u79fb\u9664\u5de5\u4f5c\u6392\u7a0b\u300c{0}\u300d' @($TaskName) }
        else { Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false; Ok 'Removed scheduled task "{0}"' '\u5df2\u79fb\u9664\u5de5\u4f5c\u6392\u7a0b\u300c{0}\u300d' @($TaskName) }
    } else { Say 'No scheduled task "{0}" found.' '\u627e\u4e0d\u5230\u5de5\u4f5c\u6392\u7a0b\u300c{0}\u300d\u3002' 'Gray' '  ' @($TaskName) }
    if (Test-Path -LiteralPath $VbsPath) {
        if ($DryRun) { Dry 'Delete {0}' '\u522a\u9664 {0}' @($VbsPath) }
        else { Remove-Item -LiteralPath $VbsPath -Force; Ok 'Deleted {0}' '\u5df2\u522a\u9664 {0}' @($VbsPath) }
    }
}

# Path of an uninstaller.exe that matches the pinned official hash: the installed one if it
# is intact, otherwise the one from a freshly downloaded, fully verified official zip, staged
# in the admin-only folder.
function Get-VerifiedUninstaller {
    $local = Join-Path $AppDir 'uninstaller.exe'
    $table = Get-ZipFileTable
    if ((Test-Path -LiteralPath $local -PathType Leaf) -and (Get-FileSha256 $local) -eq $table['uninstaller.exe']) { return $local }
    Warn '{0} is missing or is not the official file; downloading the official Raw Accel v1.7.1 and using its verified uninstaller.exe instead.' '{0} \u4e0d\u5b58\u5728\u6216\u4e0d\u662f\u5b98\u65b9\u6a94\u6848\uff1b\u6539\u70ba\u4e0b\u8f09\u5b98\u65b9 Raw Accel v1.7.1\uff0c\u4e26\u4f7f\u7528\u5176\u4e2d\u5df2\u9a57\u8b49\u7684 uninstaller.exe\u3002' @($local)
    [byte[]]$zip = Get-RawAccelZipBytes
    if (-not (Test-ZipHash $zip)) { Fail 'SHA256 mismatch for the downloaded Raw Accel zip. Nothing was removed.' '\u4e0b\u8f09\u7684 Raw Accel \u58d3\u7e2e\u6a94 SHA256 \u4e0d\u7b26\u3002\u6c92\u6709\u79fb\u9664\u4efb\u4f55\u6771\u897f\u3002' @() 4 }
    if (-not (Test-ZipEntries $zip $table)) { Fail 'The archive contents do not match the official file list. Nothing was removed.' '\u58d3\u7e2e\u6a94\u5167\u5bb9\u8207\u5b98\u65b9\u6a94\u6848\u6e05\u55ae\u4e0d\u7b26\u3002\u6c92\u6709\u79fb\u9664\u4efb\u4f55\u6771\u897f\u3002' @() 4 }
    Expand-VerifiedZip $zip $script:StageDir $table
    return (Join-Path $script:StageDir 'uninstaller.exe')
}

