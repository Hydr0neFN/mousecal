# -> @{ Action = 'apply'; Measured = [double] } or @{ Action = 'uninstall' }; throws on anything else.
# Browsers differ in how they hand over the link: mousecal://apply?m=8.2, mousecal://apply/?m=8.2,
# mousecal:apply?m=8.2 are all accepted.
function ConvertFrom-MousecalUrl([string]$Url) {
    if ([string]::IsNullOrEmpty($Url) -or $Url.Length -gt 64 -or $Url -cnotmatch '^[A-Za-z0-9:/?=.&-]+\z') { throw 'not a mousecal link' }
    if ($Url -notmatch '^mousecal:(?://)?(?<act>apply|uninstall)/?(?:\?(?<q>[^/]*))?/?\z') { throw 'not a mousecal link' }
    $act = $Matches['act'].ToLowerInvariant()
    $q = $Matches['q']
    $hasQuery = $Url.Contains('?')
    if ($act -eq 'uninstall') {
        if ($hasQuery) { throw 'uninstall takes no value' }
        return @{ Action = 'uninstall' }
    }
    if (-not $hasQuery -or $q -cnotmatch '^m=(?<n>-?[0-9]{1,2}(\.[0-9]{1,2})?)\z') { throw 'apply needs m=<degrees>' }
    $d = 0.0
    if (-not [double]::TryParse($Matches['n'], [Globalization.NumberStyles]::AllowLeadingSign -bor [Globalization.NumberStyles]::AllowDecimalPoint, [Globalization.CultureInfo]::InvariantCulture, [ref]$d)) { throw 'bad number' }
    if ([math]::Abs($d) -gt 20) { throw 'value out of range' }
    return @{ Action = 'apply'; Measured = $d }
}

